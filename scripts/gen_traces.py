#!/usr/bin/env python3
"""Generate the access-pattern traces used by the lab.

Writes (into input/ by default):
  trace.txt             the MODIFIED main trace: the original 7 sample lines,
                        then sequential, random and localized sections
  trace_sequential.txt  every thread walks memory sequentially
  trace_random.txt      every thread touches uniformly random addresses
  trace_localized.txt   every thread works in a small hot set of pages

All pattern traces use the same processes, threads, priorities and burst
lengths, so the only thing that changes between them is the access pattern.
The random seed is fixed, so the files (and every result) are reproducible.

Usage:  python3 scripts/gen_traces.py [--out input] [--seed 375]
"""
import argparse
import os
import random

PAGE = 256          # must match the simulator's page size (default 256)
SPACE = 1 << 16     # 16-bit virtual address space

# (pid, tid, burst, region base) - the workload shared by all pattern traces
THREADS = [
    (1, 1, 40, 0x1000),
    (1, 2, 24, 0x3000),
    (2, 1, 64, 0x2000),
    (2, 2, 16, 0x6000),
    (3, 1, 32, 0x4000),
    (3, 2, 48, 0x8000),
    (4, 1, 80, 0x5000),
    (4, 2, 12, 0xA000),
]
PROCESS_PRIORITY = {1: 2, 2: 1, 3: 3, 4: 2}     # lower number = higher priority
THREAD_PRIORITY = {(1, 2): 3, (4, 2): 1}        # overrides for some threads

ORIGINAL_SAMPLE = [
    "1 1 0x0043 R",
    "1 2 0x00A1 W",
    "2 1 0x0210 R",
    "3 1 0x0F0F R",
    "1 1 0x00B0 W",
    "2 2 0x0213 R",
    "3 2 0x0100 W",
]


def rw(rng, write_ratio=0.3):
    return "W" if rng.random() < write_ratio else "R"


def sequential(rng, base, n, stride=32):
    """Walk forward through memory, `stride` bytes at a time (8 accesses/page)."""
    return [((base + i * stride) % SPACE, rw(rng)) for i in range(n)]


def random_pattern(rng, base, n):
    """Uniformly random addresses anywhere in the 64 KiB address space."""
    return [(rng.randrange(SPACE), rw(rng)) for _ in range(n)]


def localized(rng, base, n, hot_pages=3, hot_prob=0.9):
    """90% of accesses hit a small hot set; the hot set moves once halfway."""
    out = []
    first = [base // PAGE + k for k in range(hot_pages)]
    second = [base // PAGE + 8 + k for k in range(hot_pages)]
    for i in range(n):
        hot = first if i < n // 2 else second
        if rng.random() < hot_prob:
            page = rng.choice(hot)
        else:                       # occasional cold access near the region
            page = base // PAGE + rng.randrange(16)
        out.append(((page * PAGE + rng.randrange(PAGE)) % SPACE, rw(rng)))
    return out


PATTERNS = {
    "sequential": sequential,
    "random": random_pattern,
    "localized": localized,
}


def header(title, lines):
    out = ["# " + "=" * 70, "# " + title]
    out += ["# " + l for l in lines]
    out += ["# Format: <pid> <thread_id> <address> <access_type> (R=read, W=write)",
            "#         PRIORITY <pid> <prio>  /  THREAD <pid> <tid> <prio>  (lower = higher)",
            "# " + "=" * 70, ""]
    return out


def priorities():
    out = ["# ---- priorities ----"]
    for pid, prio in PROCESS_PRIORITY.items():
        out.append(f"PRIORITY {pid} {prio}")
    for (pid, tid), prio in THREAD_PRIORITY.items():
        out.append(f"THREAD {pid} {tid} {prio}")
    return out + [""]


def emit(pid, tid, accesses):
    return [f"{pid} {tid} 0x{addr:04X} {t}" for addr, t in accesses]


def pattern_trace(name, seed):
    rng = random.Random(seed)
    lines = header(f"Access pattern: {name.upper()} (generated by scripts/gen_traces.py, seed {seed})",
                   [f"{len(THREADS)} threads in {len(PROCESS_PRIORITY)} processes, "
                    f"{sum(t[2] for t in THREADS)} accesses"])
    lines += priorities()
    for pid, tid, burst, base in THREADS:
        lines.append(f"# P{pid}.T{tid}: {burst} {name} accesses")
        lines += emit(pid, tid, PATTERNS[name](rng, base, burst))
        lines.append("")
    return lines


def main_trace(seed):
    """Modified input/trace.txt: original sample + one pattern per process group."""
    rng = random.Random(seed)
    lines = header("CS375 Lab 10 - modified trace with varied access patterns",
                   ["Section 0: the original 7-line sample from the handout",
                    "Section 1: P1 (both threads) SEQUENTIAL  - strided array walk",
                    "Section 2: P2 (both threads) RANDOM      - uniform over 64 KiB",
                    "Section 3: P3 (both threads) LOCALIZED   - 90% in a 3-page hot set",
                    "Section 4: P4 T1 LOCALIZED, P4 T2 SEQUENTIAL (mixed process)"])
    lines += priorities()
    lines.append("# ---- Section 0: original sample ----")
    lines += ORIGINAL_SAMPLE + [""]

    plan = {1: "sequential", 2: "random", 3: "localized"}
    section = {1: 1, 2: 2, 3: 3, 4: 4}
    current = None
    for pid, tid, burst, base in THREADS:
        name = plan.get(pid) or ("localized" if tid == 1 else "sequential")
        if section[pid] != current:
            current = section[pid]
            lines.append(f"# ---- Section {current}: process {pid} ----")
        lines.append(f"# P{pid}.T{tid}: {burst} {name} accesses")
        lines += emit(pid, tid, PATTERNS[name](rng, base, burst))
        lines.append("")
    return lines


def write(path, lines):
    with open(path, "w") as f:
        f.write("\n".join(lines).rstrip() + "\n")
    n = sum(1 for l in lines if l and not l.startswith("#") and l[0].isdigit())
    print(f"  wrote {path:32s} ({n} accesses)")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="input", help="output folder (default input)")
    ap.add_argument("--seed", type=int, default=375, help="random seed (default 375)")
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)

    print("Generating traces:")
    write(os.path.join(args.out, "trace.txt"), main_trace(args.seed))
    for i, name in enumerate(PATTERNS):
        write(os.path.join(args.out, f"trace_{name}.txt"), pattern_trace(name, args.seed + i + 1))


if __name__ == "__main__":
    main()
